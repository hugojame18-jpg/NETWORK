import { REFERRAL_RATE, payoutRate, tierBonus } from "@/lib/loyalty";

/**
 * The arithmetic of an affiliate's money, with nothing else in it.
 *
 * No database here on purpose. What an affiliate is owed is the one figure
 * that must never be wrong, so the sums live where a test can pin them down:
 * the loaders in `@/lib/data/ledger` fetch the inputs and this decides what
 * they add up to.
 */

export interface AffiliateLedger {
  publisherId: string;
  /** The rate on their contract, before the referral share. */
  commissionRate: number;
  /** What they actually keep per dollar of gross, referral share deducted. */
  rate: number;
  isReferred: boolean;
  /** Gross the network billed on their traffic. Never shown to the affiliate. */
  gross: number;
  /** Their cut of their own traffic. */
  ownEarnings: number;
  /** What they earn as a sponsor, on the gross their referrals generate. */
  referralEarnings: number;
  /** The tier bonus on their own earnings — paid by the network. */
  tierBonus: number;
  /** Everything they have earned, ever: traffic, referrals and bonus. */
  earned: number;
  /** Sum of the payouts marked as sent. */
  paid: number;
  /** Withdrawal requests opened but not yet sent. */
  pending: number;
  /** Still owed: earned minus paid. A payout never touches the stats. */
  balance: number;
  /** Balance minus what is already requested — what can still be asked for. */
  available: number;
}

export interface LedgerInput {
  publisherId: string;
  commissionRate: number;
  isReferred: boolean;
  /** Gross on their own traffic. */
  gross: number;
  /** Gross generated by the affiliates they brought in. */
  referredGross: number;
  paid: number;
  pending: number;
}

/** The arithmetic, in one place, so every caller gets the same answer. */
export function composeLedger(input: LedgerInput): AffiliateLedger {
  const rate = payoutRate(input.commissionRate, input.isReferred);
  const ownEarnings = input.gross * rate;
  const referralEarnings = input.referredGross * REFERRAL_RATE;
  // The bonus used to be shown on the rewards page and added to nothing. It
  // is money owed like the rest, so it is counted here, where the balance is.
  const bonus = tierBonus(ownEarnings);
  const earned = ownEarnings + referralEarnings + bonus;
  const balance = earned - input.paid;

  return {
    publisherId: input.publisherId,
    commissionRate: input.commissionRate,
    rate,
    isReferred: input.isReferred,
    gross: input.gross,
    ownEarnings,
    referralEarnings,
    tierBonus: bonus,
    earned,
    paid: input.paid,
    pending: input.pending,
    balance,
    available: Math.max(0, balance - input.pending),
  };
}

export function emptyLedger(publisherId: string): AffiliateLedger {
  return composeLedger({
    publisherId,
    commissionRate: 0.5,
    isReferred: false,
    gross: 0,
    referredGross: 0,
    paid: 0,
    pending: 0,
  });
}

export interface PaymentGroup {
  status: string;
  amount: number;
}

/**
 * A REJECTED request is neither money owed nor money sent, so it counts in
 * neither column. PENDING and APPROVED both mean "asked for, not yet gone".
 */
export function splitPayments(groups: PaymentGroup[]): {
  paid: number;
  pending: number;
} {
  let paid = 0;
  let pending = 0;
  for (const group of groups) {
    if (group.status === "PAID") paid += group.amount;
    else if (group.status !== "REJECTED") pending += group.amount;
  }
  return { paid, pending };
}
